export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return TOOLS.find(t => t.slug === slug);
}

export function getCategoryBySlug(slug: string) {
  return CATEGORIES.find(c => c.slug === slug);
}

export function getToolsByCategory(category: ToolCategoryType | string): ToolDefinition[] {
  return TOOLS.filter(t => t.category === category);
}

export function getPopularTools(): ToolDefinition[] {
  return TOOLS.filter(t => t.isPopular);
}

export function getFeaturedTools(): ToolDefinition[] {
  return TOOLS.filter(t => t.isFeatured);
}

export function getRelatedTools(currentTool: ToolDefinition, limit = 4): ToolDefinition[] {
  return TOOLS
    .filter(t => t.category === currentTool.category && t.id !== currentTool.id)
    .slice(0, limit);
}

export function searchTools(query: string): ToolDefinition[] {
  if (!query.trim()) return [];
  const q = query.toLowerCase().trim();
  return TOOLS.filter(t =>
    t.name.toLowerCase().includes(q) ||
    t.description.toLowerCase().includes(q) ||
    t.keywords.some(k => k.toLowerCase().includes(q)) ||
    t.category.toLowerCase().includes(q)
  );
}
